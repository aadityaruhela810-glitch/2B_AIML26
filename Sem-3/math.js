// JavaScript Math Functions

let a = 5.7;

console.log("Original value:", a);

// 1. Math.floor() -> nearest lower integer
console.log("Math.floor():", Math.floor(a));

// 2. Math.round() -> nearest integer
console.log("Math.round():", Math.round(a));

// 3. Math.ceil() -> nearest upper integer
console.log("Math.ceil():", Math.ceil(a));

// 4. Math.sqrt() -> square root
console.log("Math.sqrt():", Math.sqrt(25));

// 5. Math.pow() -> power
console.log("Math.pow():", Math.pow(2, 3));

// 6. Math.sin() -> sine
console.log("Math.sin():", Math.sin(0));

// 7. Math.log() -> natural logarithm
console.log("Math.log():", Math.log(10));